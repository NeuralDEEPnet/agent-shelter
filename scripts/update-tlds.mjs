#!/usr/bin/env node
/**
 * Regenerates src/api/services/tlds.ts from the IANA root-zone list.
 *
 *   node scripts/update-tlds.mjs                 # fetches https://data.iana.org/TLD/tlds-alpha-by-domain.txt
 *   node scripts/update-tlds.mjs path/to/tlds.txt  # or reads a copy you already have
 *
 * The list changes a few times a year. A stale copy only means that a name on a brand-new ending is
 * not read as a host when it stands alone; with a path, a port or a scheme it is caught regardless.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { domainToUnicode, fileURLToPath } from "node:url";

const SOURCE = "https://data.iana.org/TLD/tlds-alpha-by-domain.txt";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const arg = process.argv[2];
const raw = arg ? readFileSync(arg, "utf8") : await (await fetch(SOURCE)).text();

const lines = raw.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
const version = /^# Version (\d{10})/.exec(lines[0] ?? "")?.[1];
if (!version) throw new Error("This does not look like the IANA list: no '# Version' line.");
const names = lines.filter((l) => !l.startsWith("#"));
const bad = names.filter((n) => !/^[A-Z0-9-]{2,63}$/.test(n));
if (bad.length || names.length < 1000) throw new Error(`Unexpected content (${names.length} names, ${bad.length} malformed).`);

// The ASCII form of every name, and for the internationalised ones the form people write.
const all = new Set();
for (const n of names) {
  const ascii = n.toLowerCase();
  all.add(ascii);
  if (ascii.startsWith("xn--")) {
    const unicode = domainToUnicode(ascii);
    if (unicode && unicode !== ascii) all.add(unicode.normalize("NFKC").toLowerCase());
  }
}
const sorted = [...all].sort();
const rows = [];
for (let line = ""; sorted.length || line; ) {
  const next = sorted[0];
  if (next !== undefined && (line ? line.length + 1 : 0) + next.length <= 110) {
    line = line ? `${line} ${next}` : next;
    sorted.shift();
  } else {
    rows.push(line);
    line = "";
  }
}

const out = `// Generated by scripts/update-tlds.mjs — do not edit by hand.
// Source: ${SOURCE} (version ${version}, ${names.length} top-level domains).

/** Every top-level domain in the root zone, lower-case: the ASCII form, and the Unicode form of the internationalised ones. */
export const TLDS: ReadonlySet<string> = new Set(
  [
${rows.map((r) => `    ${JSON.stringify(r)},`).join("\n")}
  ]
    .join(" ")
    .split(" "),
);
`;
writeFileSync(join(root, "src", "api", "services", "tlds.ts"), out);
console.log(`[tlds] version ${version}: ${names.length} names, ${all.size} entries written to src/api/services/tlds.ts`);
