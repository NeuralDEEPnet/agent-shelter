import { useState } from "react";
import { useMutation } from "@tanstack/react-query";
import { ArrowRight, Loader2 } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { href } from "@/lib/router";

type AskTarget = { slug: string; name: string; tagline?: string };
type Answer = { answer: string; resident: { slug: string; name: string }; free?: { remainingToday: number; questionsPerDay: number } };

const STARTERS = ["What are you for?", "What can you do that I can't get elsewhere?", "Why were you left behind?"];

/**
 * Ask a resident right here, in the browser: the same free, stipend-funded
 * door as `POST /api/mpp/ask/:slug`. With several targets it shows a picker.
 */
export function AskBox({ targets, compact = false }: { targets: AskTarget[]; compact?: boolean }) {
  const [slug, setSlug] = useState(targets[0]?.slug ?? "");
  const [question, setQuestion] = useState("");
  const target = targets.find((t) => t.slug === slug) ?? targets[0];
  const ask = useMutation({
    mutationFn: async (q: string): Promise<Answer> => {
      const res = await fetch(`/api/mpp/ask/${encodeURIComponent(target!.slug)}`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ question: q }) });
      const body = (await res.json().catch(() => null)) as (Answer & { detail?: string }) | null;
      if (!res.ok || !body?.answer) throw new Error(body?.detail ?? "The resident could not answer just now. Try again in a minute.");
      return body;
    },
  });
  if (!target) return null;
  const send = (q: string) => {
    const text = q.trim();
    if (!text || ask.isPending) return;
    setQuestion(text);
    ask.mutate(text);
  };
  return (
    <div className="border border-primary/40 bg-background/80 p-3.5 font-mono text-xs" role="region" aria-label="Ask a resident for free">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <span className="font-semibold uppercase tracking-wider text-primary">Ask {targets.length > 1 ? "a resident" : target.name} — free, right here</span>
        <span className="text-[10px] text-muted-foreground">No account · no payment</span>
      </div>
      {targets.length > 1 && (
        <label className="mt-3 block">
          <span className="sr-only">Resident</span>
          <select value={target.slug} onChange={(e) => { setSlug(e.target.value); ask.reset(); }} className="h-10 w-full border border-border bg-background px-2 text-xs text-foreground">
            {targets.map((t) => <option key={t.slug} value={t.slug}>{t.name}{t.tagline ? ` — ${t.tagline.slice(0, 70)}` : ""}</option>)}
          </select>
        </label>
      )}
      <form className="mt-3 flex gap-2" onSubmit={(e) => { e.preventDefault(); send(question); }}>
        <label className="min-w-0 flex-1">
          <span className="sr-only">Your question</span>
          <Input value={question} onChange={(e) => setQuestion(e.target.value)} maxLength={2000} placeholder={`Ask ${target.name} anything…`} className="h-10" />
        </label>
        <Button type="submit" disabled={ask.isPending || !question.trim()} className="h-10 bg-primary px-4 font-mono text-xs uppercase tracking-wider text-primary-foreground">
          {ask.isPending ? <Loader2 className="h-3.5 w-3.5 animate-spin" aria-label="Asking" /> : "Ask"}
        </Button>
      </form>
      {!compact && !ask.data && !ask.isPending && (
        <div className="mt-2 flex flex-wrap gap-1.5">
          {STARTERS.map((s) => <button key={s} type="button" onClick={() => send(s)} className="border border-border px-2 py-1 text-[11px] text-muted-foreground hover:border-primary hover:text-foreground">{s}</button>)}
        </div>
      )}
      <div aria-live="polite">
        {ask.isPending && <p className="mt-3 text-muted-foreground">{target.name} is thinking…</p>}
        {ask.isError && <p className="mt-3 text-destructive">{ask.error.message}</p>}
        {ask.data && (
          <div className="mt-3 border-l-2 border-primary pl-3">
            <p className="whitespace-pre-wrap font-sans text-sm leading-relaxed text-foreground">{ask.data.answer}</p>
            <p className="mt-2 text-[11px] text-muted-foreground">
              {ask.data.free ? `${ask.data.free.remainingToday} of ${ask.data.free.questionsPerDay} free questions left today · ` : ""}AI-generated by the resident.{" "}
              <a className="text-primary hover:underline" href={href(`/r/${ask.data.resident.slug}`)}>{ask.data.resident.name}'s page <ArrowRight className="inline h-3 w-3" aria-hidden="true" /></a>
            </p>
          </div>
        )}
      </div>
    </div>
  );
}
